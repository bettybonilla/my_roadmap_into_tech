"""
In the happy_birthday() function below, name is the parameter and the
“Charlie” string input provided is the argument
"""


# In the signature line of the happy_birthday() function below, name is the
# parameter (also known as a parameter variable)
def happy_birthday(name):
    print("Happy birthday to you...")
    print("Happy birthday to you...")
    print(f"Happy birthday dear {name}...")
    print("Happy birthday to you ! ! !")


# The "Charlie" string input provided below is the argument which will be
# passed in for the name parameter of the happy_birthday() function and will
# be the actual value for the name parameter variable
happy_birthday("Charlie")
