"""
Below the happy_birthday() function uses the name parameter to accept the name
provided and insert it into the happy birthday song
- NOTE: If you try to call a parameter outside of your function, you will get
an error
"""


def happy_birthday(name):
    print("Happy birthday to you...")
    print("Happy birthday to you...")
    print(f"Happy birthday dear {name}...")
    print("Happy birthday to you ! ! !")


happy_birthday("Charlie")
