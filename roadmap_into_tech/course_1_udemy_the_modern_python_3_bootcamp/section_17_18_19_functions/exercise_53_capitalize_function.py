"""
Write a function called capitalize
- This function accepts a string and returns the same string with the first
letter capitalized - You may want to use slices to help you out
    - Ex:
    1. capitalize("jamaica")  # "Jamaica"
    2. capitalize("chicken")  # "Chicken"
"""


def capitalize(word: str) -> str:
    return word.capitalize()


print(capitalize("jamaica"))
print(capitalize("chicken"))
print(capitalize("tim"))
print(capitalize("matt"))
