# Set the variable called greeting to some greeting, e.g. “hello”
greeting = "Hello"

# Set the variable called name to some name, e.g. “Heisenberg”
name = "Heisenberg"

# Then set the variable called greet_name so that it concatenates greeting,
# name, and a space “ “ between them.
greet_name = greeting + " " + name
print(greet_name)
