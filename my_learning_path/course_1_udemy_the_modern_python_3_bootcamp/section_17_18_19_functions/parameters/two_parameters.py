"""
The functions below both use two parameters and, as mentioned, your parameters
can be named anything you want
"""


# The add() function adds the a and b parameters
def add(a, b):
    return a + b


# To call the function above, provide 2 values separated by a comma
print(add(2, 2))
print(add(2, 4))
print(add(5, 5))


# The multiply() function multiplies the first and second parameters
def multiply(first, second):
    return first * second


# To call the function above, provide 2 values separated by a comma
print(multiply(2, 2))
print(multiply(2, 4))
print(multiply(5, 5))
